export const UNCOMMITTED_PROMPT =
  "请在保持功能完全不变的前提下，简化当前的代码改动（包括已暂存、未暂存和未跟踪的文件）。";

/** 拿到 merge base 时给出确定的 diff 命令，避免模型自己猜。 */
export function baseBranchPrompt(branch, mergeBaseSha) {
  if (mergeBaseSha) {
    return (
      `请简化当前分支相对基线分支 '${branch}' 的代码改动。` +
      `本次比较的 merge base 提交是 ${mergeBaseSha}。` +
      `执行 \`git diff ${mergeBaseSha}\` 查看相对 ${branch} 的改动，` +
      "然后只对这些改动做简化，并保持功能完全不变。"
    );
  }
  return (
    `请简化当前分支相对基线分支 '${branch}' 的代码改动。` +
    "先求出当前分支与 " +
    `${branch} 上游分支的 merge base，例如 \`git merge-base HEAD "$(git rev-parse --abbrev-ref "${branch}@{upstream}")"\`，` +
    `然后对该 SHA 执行 \`git diff\`，查看将要合入 ${branch} 分支的改动，` +
    "只对这些改动做简化，并保持功能完全不变。"
  );
}

export function commitPrompt(sha, title) {
  const scope = title ? `提交 ${sha}（"${title}"）` : `提交 ${sha}`;
  return (
    `请简化 ${scope} 引入的代码。` +
    `先用 \`git show ${sha}\` 检视改动，` +
    "然后只对这部分代码做简化，并保持功能完全不变。"
  );
}

/** 无 git 上下文时的兜底：由用户点名文件或目录。 */
export function pathsPrompt(paths) {
  return `请简化 ${paths} 中的代码。先读代码，然后在保持功能完全不变的前提下做简化。`;
}


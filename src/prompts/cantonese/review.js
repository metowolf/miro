export const UNCOMMITTED_PROMPT =
  "請審查當前嘅代碼改動（包括已暫存、未暫存同未追蹤嘅檔案），並且按優先級俾出問題清單。";

/** 拿到 merge base 时给出确定的 diff 命令，避免模型自己猜。 */
export function baseBranchPrompt(branch, mergeBaseSha) {
  if (mergeBaseSha) {
    return (
      `請審查當前分支相對基線分支 '${branch}' 嘅代碼改動。` +
      `今次比較嘅 merge base 提交係 ${mergeBaseSha}。` +
      `執行 \`git diff ${mergeBaseSha}\` 睇相對 ${branch} 嘅改動。` +
      "並且按優先級俾出可執行嘅問題清單。"
    );
  }
  return (
    `請審查當前分支相對基線分支 '${branch}' 嘅代碼改動。` +
    "先求出當前分支同 " +
    `${branch} 上游分支嘅 merge base，例如 \`git merge-base HEAD "$(git rev-parse --abbrev-ref "${branch}@{upstream}")"\`，` +
    `然後對該 SHA 執行 \`git diff\`，睇將會合入 ${branch} 分支嘅改動。` +
    "並且按優先級俾出可執行嘅問題清單。"
  );
}

export function commitPrompt(sha, title) {
  const scope = title ? `提交 ${sha}（"${title}"）` : `提交 ${sha}`;
  return `請審查 ${scope} 引入嘅代碼改動，並且按優先級俾出可執行嘅問題清單。`;
}

